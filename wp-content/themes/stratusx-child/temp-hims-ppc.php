          <summary>Can Healthray HIMS be deployed on-premise for government or trust hospitals?</summary>
          <div class="answer">Yes. The same platform deploys on cloud, on-premise or hybrid, so hospitals with data-residency conditions, tender requirements or limited connectivity can run it inside their own infrastructure. Our team supports tender documentation, technical compliance sheets and phased institutional rollouts.</div>

          <div class="answer">Pricing depends on bed count, number of facilities, modules and deployment model - a 50-bed single hospital costs far less than a multi-city chain with on-premise servers. Healthray offers module-wise and enterprise plans with a free trial. Book a demo and we will share a quote matched to your hospital's size and rollout plan.</div>
